'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..'),crypto=require('node:crypto').webcrypto;
const ctx={crypto,TextEncoder,JSON,Date};ctx.globalThis=ctx;
vm.runInNewContext(fs.readFileSync(path.join(root,'js/document-control.js'),'utf8'),ctx);
const dc=ctx.AuditDocumentControl;
(async()=>{
 const audit={schemaVersion:3,meta:{client:'Example',project:'Infrastructure audit'},findings:[],evidence:[]};
 assert.equal(dc.normalize(undefined).status,'draft');
 await dc.confirm(audit,'Responsible Auditor');
 assert.equal(audit.documentControl.status,'confirmed');
 assert.equal(audit.documentControl.revision,1);
 assert(await dc.verify(audit));
 audit.meta.project='Unauthorized edit';
 assert.equal(await dc.verify(audit),false);
 audit.meta.project='Infrastructure audit';
 await dc.beginAmendment(audit,'Responsible Auditor','Correct documented scope and attach complementary information');
 assert.equal(audit.documentControl.status,'amending');
 await assert.rejects(dc.finalizeAmendment(audit),/No hay modificaciones/);
 audit.meta.scope='Additional information';
 const result=await dc.finalizeAmendment(audit);
 assert.equal(result.revision,2);
 assert(result.changes.some(item=>item.field==='meta.scope'));
 assert.equal(audit.documentControl.status,'confirmed');
 assert(await dc.verify(audit));
 const imported=JSON.parse(JSON.stringify(audit));
 assert.equal(dc.normalize(imported.documentControl).revision,2);
 assert(await dc.verify(imported));
 const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
 const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
 const app=fs.readFileSync(path.join(root,'js/app.js'),'utf8');
 for(const name of ['audit-workbench.sh','audit-workbench.ps1','index.html','sw.js'])
 assert(fs.readFileSync(path.join(root,name),'utf8').includes('document-control.js'),name+' must include module');
 assert(html.indexOf('js/document-control.js')<html.indexOf('js/app.js'));
 assert(sw.includes('v36-document-control'));
 assert(app.includes('persist(true)')&&app.includes('await docControl.verify(state)'));
 console.log('PASS document confirmation, detection, amendments, persistence and package');
})().catch(error=>{console.error(error);process.exitCode=1});
