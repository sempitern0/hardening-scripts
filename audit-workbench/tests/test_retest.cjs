'use strict';
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path'),assert=require('node:assert/strict');
const env={};env.globalThis=env;
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../audit-retest.js'),'utf8'),env);
const api=env.AuditRetest, make=()=>'REV-001';
let finding={id:'FND-001',status:'Abierto',verification:'Comprobar configuración segura',retests:[]};
let entries=[{_key:'ev1',id:'EVD-001'}];
assert.equal(api.outcome(finding),'not-reviewed');
assert.throws(()=>api.record(finding,{date:'2026-13-22',result:'verified',notes:'Revisión terminada',by:'Auditor'},entries,make),/fecha/);
assert.throws(()=>api.record(finding,{date:'2026-10-12',result:'verified',notes:'Breve',by:'Auditor'},entries,make),/al menos/);
const a=api.record(finding,{date:'2026-10-12',result:'verified',notes:'Se ha verificado el ajuste de ACL.',by:'Auditor',evidenceKey:'ev1'},entries,make);
api.apply(finding,a);
assert.equal(finding.status,'Cerrado');assert.equal(api.outcome(finding),'verified');
const b=api.record(finding,{date:'2026-10-13',result:'unverified',notes:'No se dispone de acceso en esta visita.',by:'Auditor'},entries,()=> 'REV-002');
api.apply(finding,b);
assert.equal(finding.status,'Cerrado');assert.equal(api.outcome(finding),'unverified');
const c=api.record(finding,{date:'2026-10-14',result:'reopened',notes:'La configuración vuelve a incumplir el control.',by:'Auditor'},entries,()=> 'REV-003');
api.apply(finding,c);
assert.equal(finding.status,'Abierto');assert.equal(finding.retests.length,3);
const roundtrip=JSON.parse(JSON.stringify(finding));
assert.equal(api.normalize(roundtrip.retests).length,3);
const counts=api.summary({findings:[finding,{status:'Riesgo aceptado'},{status:'Mitigado',retests:[]}]});
assert.deepEqual(Array.from(['total','verified','reopened','accepted','not-reviewed'],k=>counts[k]),[3,0,1,1,1]);
assert.equal(api.normalize([{date:'2026-01-01',result:'not-real'},{date:'2026-02-28',result:'verified',notes:'x'.repeat(9000)}])[0].notes.length,4000);
console.log('PASS retest validation, history, status transitions, JSON roundtrip');
