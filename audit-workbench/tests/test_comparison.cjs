'use strict';
const assert=require('node:assert/strict');const fs=require('node:fs');const vm=require('node:vm');const path=require('node:path');
const root=path.resolve(__dirname,'..'),context=vm.createContext({});
for(const name of ['js/audit-retest.js','js/audit-comparison.js'])vm.runInContext(fs.readFileSync(path.join(root,name),'utf8'),context);
const c=context.AuditComparison,r=context.AuditRetest;
const make=(key,severity='Alta')=>({_key:key,id:key,title:'Hallazgo '+key,severity,status:'Abierto',retests:[]});
const sample={findings:[make('F-1'),make('F-2','Crítica'),make('F-3','Baja')]};
assert.equal(c.compare(sample,r).verifiedPercent,null,'no metric without history');
const baseline=c.capture(sample,'before-first-retest','2026-10-10T10:00:00.000Z');
assert.equal(c.normalizeBaseline(baseline).findings.length,3);
sample.followupBaseline=baseline;
assert.equal(c.compare(sample,r).verifiedPercent,0);
sample.findings[0].verification='Comprobar';
r.apply(sample.findings[0],r.record(sample.findings[0],{result:'verified',date:'2026-10-11',by:'Auditor prueba',notes:'Verificado el acceso correcto tras la corrección.'},[],()=> 'rev-1'));
sample.findings[1].status='Riesgo aceptado';
let cmp=c.compare(sample,r);assert.equal(cmp.counts.verified,1);assert.equal(cmp.counts.accepted,1);assert.equal(cmp.verifiedPercent,33);assert.equal(cmp.priorityNotVerified,1,'accepted is still risk');
sample.findings.push(make('F-4','Crítica'));
cmp=c.compare(sample,r);assert.equal(cmp.added,1);assert.equal(cmp.initialTotal,3);assert.equal(cmp.decisions[0].id,'F-4');
sample.findings.splice(2,1);cmp=c.compare(sample,r);assert.equal(cmp.counts.missing,1);assert.equal(cmp.verifiedPercent,33);
sample.findings[0].status='Abierto';assert.equal(c.compare(sample,r).counts.inconsistent,1);
assert.equal(c.normalizeBaseline({...baseline,findings:[baseline.findings[0],baseline.findings[0]]}),null,'duplicate must fail');
assert.equal(c.normalizeBaseline({...baseline,findings:Array.from({length:501},(_,i)=>({key:String(i)}))}),null,'bounds');
const restored=c.normalizeBaseline(JSON.parse(JSON.stringify(baseline)));assert.equal(restored.findings[1].severity,'Crítica');
console.log('PASS executive comparisons: baseline, verified %, accepted risk, missing/new, inconsistencies, import guards');
