'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const context={};context.globalThis=context;
for(const file of ['audit-relations.js','audit-evidence-images.js','audit-quality.js'])
  vm.runInNewContext(fs.readFileSync(path.join(root,'js',file),'utf8'),context);
const photos=context.AuditEvidenceImages, quality=context.AuditQuality, relations=context.AuditRelations;
const fake='data:image/jpeg;base64,'+'A'.repeat(200);
let row={id:'EVD-001',image:'',attachments:[]};
const first={image:fake,fileName:'original.jpg',fileBytes:110,fileSha256:'a'.repeat(64)};
const second={image:fake,fileName:'extra.jpg',fileBytes:120,fileSha256:'b'.repeat(64)};
photos.add(row,[first,second]);
assert.equal(row.fileName,'original.jpg');
assert.equal(photos.list(row).length,2);
const serialized=JSON.parse(JSON.stringify(row));
assert.equal(photos.list(serialized).length,2,'New JSON carries additional images');
assert.equal(photos.list({...serialized,attachments:undefined}).length,1,'Old JSON keeps the original photo');
photos.remove(row,0);
assert.equal(row.fileName,'extra.jpg','Removing the first photo promotes the next one');
assert.equal(photos.list(row).length,1);
assert.throws(()=>photos.add(row,Array(10).fill(second)),/10 imágenes/);
assert.throws(()=>photos.normalize([{image:'data:image/svg+xml;base64,AAAA'}]),/no válida/);
const base={meta:{client:'Cliente',project:'Proyecto',scope:'Activo',rules:'Autorización',auditTeam:[{name:'Auditor'}]},
 final:{executive:'Resultado',signoff:'Auditor'},controls:[{id:'CTRL-001',status:'No verificado'}],findings:[],evidence:[]};
const reviewed=quality.review(base,relations,{mode:'final'});
assert(reviewed.warnings.some(i=>i.code==='CONTROLES_PENDIENTES'));
assert(!reviewed.blockers.some(i=>i.code==='CONTROLES_PENDIENTES'));
assert(quality.review({...base,meta:{...base.meta,scope:''}},relations,{mode:'final'}).blockers.some(i=>i.code==='ALCANCE'));
const app=fs.readFileSync(path.join(root,'js/app.js'),'utf8');
assert(app.includes('multiple data-finding-image-key=')&&app.includes('multiple data-image-index='));
assert(app.includes('state.evidence.unshift(record)'),'Photos from findings create a linked evidence if missing');
assert(app.includes("relations.linkedEvidence(state,'findings',key)"),'Existing evidence must be reused');
assert(app.includes('await Promise.all(photos.map(prepareEvidenceImage))'),'Batch conversion must finish before mutation');
assert(app.includes('evidenceImages.list(row).map'),'The PDF must render all photos in a single evidence');
assert(app.indexOf('const activeChapters=chapters.filter')<app.indexOf("const toc=section("),'PDF index must use initialized chapters');
const dc=fs.readFileSync(path.join(root,'js/document-control.js'),'utf8');
assert(dc.includes("key==='image'"),'Amendment diff should exclude image payload but preserve attachment metadata');
assert(!dc.includes("key==='attachments'"),'Attachments metadata must be retained in amendments');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
assert(sw.includes("'./js/audit-evidence-images.js'"));
console.log('PASS multi-image evidence, v3 legacy, authorizations, delivery warning, PDF and offline assets');
