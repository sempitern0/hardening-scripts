'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '..', 'js/audit-relations.js'), 'utf8');
const ctx = {globalThis: {}};
vm.runInNewContext(source, ctx, {filename:'js/audit-relations.js'});
const rel = ctx.globalThis.AuditRelations;
assert.ok(Object.isFrozen(rel));
assert.equal(rel.nextCode([{id:'EVD-001'},{id:'EVD-003'}], 'evidence'), 'EVD-002');
assert.equal(rel.nextCode([{id:'ACT-001'}], 'assets'), 'ACT-002');
assert.deepEqual(JSON.parse(JSON.stringify(rel.normalizeLinks({assets:['a','a',null,'b'],controls:['c']}))), {assets:['a','b'],controls:['c'],findings:[]});
const audit = {meta:{reportId:'AUD-012'},assets:[{_key:'srv-1',id:'ACT-001',name:'Servidor principal'}],controls:[{_key:'control-1',id:'CTRL-001'}],findings:[{_key:'finding-1',id:'FND-001'}],evidence:[{_key:'ev-1',id:'EVD-001',title:'Captura',fileName:'imagen.png',fileBytes:100,fileSha256:'b'.repeat(64),links:{assets:['srv-1'],findings:['finding-1'],controls:[]}}]};
assert.equal(rel.linkedEvidence(audit,'findings','finding-1').length,1);
assert.deepEqual(JSON.parse(JSON.stringify(rel.referenceProblems(audit))),[]);
assert.equal(rel.evidenceManifest(audit).evidence[0].originalSha256,'b'.repeat(64));
audit.assets=[];
assert.equal(rel.referenceProblems(audit).length,1);
audit.evidence[0].links.assets=[];
audit.evidence.push({_key:'ev-2',id:'EVD-001',links:null});
assert.match(rel.referenceProblems(audit).join(' '),/repetido/);
console.log('PASS: stable IDs, links, audit diagnostics and SHA-256 manifest');
