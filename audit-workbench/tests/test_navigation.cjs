'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const app=read('js/app.js'),html=read('index.html'),css=read('css/styles.css'),sw=read('sw.js');
assert(app.includes("if(['records','backups','online','settings','connections','glossary'].includes(section)||nav.some"),'Glossary must be an allowed destination');
assert(app.includes("page==='glossary'?renderGlossary()"),'Glossary must render');
assert(app.includes("button.classList.toggle('active',active)"),'Active main-menu navigation required');
for(const page of ['records','backups','settings','connections','glossary'])assert(html.includes('data-go="'+page+'"'),'Missing '+page);
assert((html.match(/class="nav-icon"/g)||[]).length===5,'Expected five SVG icons');
assert(!/<span class="nav-mark">/.test(html),'Global menu must not use font glyphs');
assert(css.includes('#global-navigation button .nav-icon'),'SVG sizing must be defined');
assert(sw.includes('audit-workbench-shell-v45-single-json'),'PWA cache must update');
console.log('PASS glossary navigation, five sharp SVG icons and PWA cache');
