'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),context={crypto:crypto.webcrypto};context.globalThis=context;
vm.runInNewContext(fs.readFileSync(path.join(root,'js/audit-identifiers.js'),'utf8'),context);
const ids=context.AuditIdentifiers,date=vm.runInNewContext('new Date(2026,9,14)',context);
const a=ids.generate([],'AUD',{date});
const b=ids.generate([{audit:{meta:{reportId:a}}}],'AUD',{date});
assert.match(a,/^AUD-20261014-[A-F0-9]{24}$/);
assert.notEqual(a,b);
assert(ids.collides(a,[{id:'1',audit:{meta:{reportId:a}}}]));
assert(!ids.collides(a,[{id:'1',audit:{meta:{reportId:a}}}],'1'));
for(const type of ['assets','controls','findings','evidence'])assert(ids.isLockedField(type,'id'));
assert(ids.isLockedField('meta','reportId'));
assert(!ids.isLockedField('cves','id'),'External CVE identifiers must stay editable');
assert(!ids.isLockedField('assets','serial'));
assert.throws(()=>ids.generate([],'*INVALID*',{date}),/prefijo/);
const script=fs.readFileSync(path.join(root,'js/app.js'),'utf8');
assert(script.includes('readonly aria-readonly="true" class="identifier-readonly"'));
assert(script.includes('identifiers.generate(records,settings.prefix'));
assert(script.includes('copy.documentControl=null'));
assert(script.includes('identifiers.collides(audit.meta.reportId,records)'));
assert(!script.includes('state.meta.reportId=nextReportId(t.value)'));
const html=fs.readFileSync(path.join(root,'index.html'),'utf8'),sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
assert(html.includes('js/audit-identifiers.js')&&sw.includes("'./js/audit-identifiers.js'"));
require('./support/sw-contract.js').assertCached('js/audit-identifiers.js');
for(const file of ['audit-workbench.sh','audit-workbench.ps1'])assert(fs.readFileSync(path.join(root,file),'utf8').includes('audit-identifiers.js'));
console.log('PASS read-only local references, uniqueness, imports, duplication and offline packaging');
