'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.resolve(__dirname,'..'),ctx={};ctx.globalThis=ctx;
vm.runInNewContext(fs.readFileSync(path.join(root,'js/input-guidance.js'),'utf8'),ctx);
const g=ctx.AuditInputGuidance;
assert.equal(g.detect('+34 612 345 678').id,'ES');
assert.equal(g.detect('+1 202 555 0123').id,'US');
assert.equal(g.international('612345678','ES'),'+34 612 345 678');
assert.equal(g.international('2025550123','US'),'+1 202 555 0123');
assert.equal(g.placeholder('meta','clientTaxId',{clientIdType:'DNI / NIF persona física'}),'12345678Z');
assert.equal(g.placeholder('meta','contactId',{contactIdType:'NIE'}),'X1234567L');
assert.equal(g.placeholder('settings','taxId',{taxType:'NIF entidad / CIF'}),'B12345678');
assert.equal(g.validate('+34 612 345 678'),'');
assert(g.validate('+34 612 345').includes('9 dígitos'),'Incomplete number should be identified');
assert(g.validate('+0 12345678').includes('cero'),'Invalid dial code should be identified');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const bash=fs.readFileSync(path.join(root,'audit-workbench.sh'),'utf8');
const ps=fs.readFileSync(path.join(root,'audit-workbench.ps1'),'utf8');
for(const value of [html,sw,bash,ps])assert(value.includes('input-guidance.js'),'Module missing from distribution');
assert(html.indexOf('js/input-guidance.js')<html.indexOf('js/app.js'));
assert(sw.includes('v30-secure-distribution'));
assert(fs.readFileSync(path.join(root,'css/styles.css'),'utf8').includes('.phone-widget'));
console.log('PASS offline placeholders, international telephone formats and packaging');
