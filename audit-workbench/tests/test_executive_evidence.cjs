'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync(__dirname+'/../js/app.js','utf8');
require('../js/audit-evidence-images.js');require('../js/audit-relations.js');
const image='data:image/jpeg;base64,'+'A'.repeat(40);
const other='data:image/jpeg;base64,'+'B'.repeat(40);
const state={evidence:[{id:'E1',image,links:{findings:['key']}},{id:'E2',image:other},{id:'E3',image:other}]};
const context={state,evidenceImages:globalThis.AuditEvidenceImages,relations:globalThis.AuditRelations,str:v=>String(v||''),html:v=>String(v||'').replaceAll('<','&lt;').replaceAll('"','&quot;')};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('  function executiveFindingImages('),source.indexOf("  let printMode='audit'")),context);
const render=f=>context.executiveFindingImages({_key:'key',...f});
assert.equal((render({}).match(/<figure/g)||[]).length,1);
assert.equal(render({executiveImages:'No mostrar'}),'');
assert.equal(render({executiveImages:'Seleccionadas (máximo 2)',executiveEvidenceIds:'E3'}),'','Unlinked evidence must not leak');
let result=render({evidenceIds:'E2',executiveImages:'Seleccionadas (máximo 2)',executiveEvidenceIds:'E2,E1,E2',executiveCaption:'<script>'});
assert.equal((result.match(/<figure/g)||[]).length,2);
assert(result.indexOf(other)<result.indexOf(image),'Explicit order');
assert(!result.includes('<script>'),'Escape captions');
assert.equal((render({evidenceIds:'E2 E3',executiveImages:'Seleccionadas (máximo 2)',executiveEvidenceIds:'E2 E3'}).match(/<figure/g)||[]).length,1,'Deduplicate images');
assert.equal(render({evidenceIds:'E2',executiveImages:'Seleccionadas (máximo 2)',executiveEvidenceIds:'deleted'}),'','Deleted selection must not silently substitute another image');
console.log('PASS executive evidence: default, exclusion, links, order, cap, escaping, duplicates and stale selection');
