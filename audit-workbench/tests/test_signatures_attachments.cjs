'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const app=fs.readFileSync(path.join(root,'js/app.js'),'utf8');
const team=fs.readFileSync(path.join(root,'css/team.css'),'utf8');
const print=fs.readFileSync(path.join(root,'css/print.css'),'utf8');
const source=fs.readFileSync(path.join(root,'js/software-catalog.js'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
const env={};env.globalThis=env;vm.runInNewContext(source,env);
const companies=Array.from(env.AuditSoftwareCatalog.PUBLISHERS);
assert(companies.length>=130,'Expected expanded catalog');
for(const name of ['Google','Oracle','Software DELSOL','VideoLAN','AnyDesk Software GmbH','WinRAR / win.rar GmbH'])
 assert(companies.includes(name),'Missing software publisher '+name);
assert.equal(new Set(companies).size,companies.length);
assert(app.includes("const signature=safeSignature")||app.includes("signature:safeSignature(raw.signature)"),'Signature image must be validated on import');
assert(app.includes("signatureProof"),'Signature metadata must survive export/import normalization');
assert(app.includes("normalizeAuditTeam(raw.meta.auditTeam)"),'Historical snapshots must remain intact');
assert(app.includes("const image=await resizeImage(t.files[0],900,.82,320000,2)"),'Signature rasterization must be bounded');
assert(app.includes("if(!/\\.(pdf|p7s|p7m|asice)$/i.test(file.name)"),'External proof should be restrictive');
assert(app.includes("renderSignaturePage(meta,reportDeliveryMode)"),'Technical and executive reports must include signature page');
assert(app.includes("renderSignaturePage(meta,'draft')"),'Retest report must include signature page');
assert(print.includes('.report-signature-page')&&print.includes('break-before:page'),'Signatures must start a print page');
assert(team.includes('.member-signature'),'Signature settings missing styling');
assert(app.includes('data-finding-image-key'),'Finding should accept image uploads directly');
assert(app.includes("links:relations.normalizeLinks({findings:[finding._key]})"),'Evidence must link to finding');
assert(app.includes('state.evidence.unshift(evidence)'),'Adding a capture should create a new evidence');
assert(app.includes("if(state.documentControl?.status==='confirmed')throw Error("),'Confirmed audit must reject uploads');
assert(app.includes("prepareEvidenceImage(t.files[0])"),'Uploads must reuse bounded raster conversion');
assert(app.includes("fileSha256,sha256:fileSha256"),'Original image digest must be tracked');
assert(sw.includes('v48-auditor-signatures'),'PWA shell should have been versioned');
console.log('PASS signature snapshots, bounded images, automatic links, offline publishers and print signing page');
