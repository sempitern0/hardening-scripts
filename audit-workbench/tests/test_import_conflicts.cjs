'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const code=fs.readFileSync(path.join(root,'js/audit-import-plan.js'),'utf8');
const context={};context.globalThis=context;vm.runInNewContext(code,context);
const plan=context.AuditImportPlan.plan;
const rec=(id,ref,project)=>({id,createdAt:'2025-01-01',audit:{meta:{reportId:ref,project}}});
const audit=(ref,project)=>({meta:{reportId:ref,project}});
const existing=[rec('db-key-1','AUD-123','Versión anterior'),rec('db-key-2','AUD-456','Otro trabajo')];
const single=plan(existing,[audit(' aud-123 ','Nueva versión')]);
assert.equal(single.replaced.length,1);
assert.equal(single.added.length,0);
assert.equal(single.entries[0].existing.id,'db-key-1');
assert.equal(single.entries[0].audit.meta.project,'Nueva versión');
const mixed=plan(existing,[audit('aud-456','Sustituir'),audit('AUD-NEW','Crear')]);
assert.equal(mixed.replaced.length,1);
assert.equal(mixed.added.length,1);
assert.equal(mixed.entries[0].existing.id,'db-key-2');
assert.equal(mixed.entries[1].existing,null);
assert.throws(()=>plan(existing,[audit('AUD-123','Uno'),audit('aud-123','Dos')]),/repetida/);
assert.throws(()=>plan([existing[0],rec('db-key-3','aud-123','Duplicado')],[audit('AUD-123','A')]),/repetida/);
assert.throws(()=>plan(existing,[audit('','Falta referencia')]),/sin referencia/);
assert.throws(()=>plan(existing,Array(251).fill(audit('AUD-OTHER','Limit'))),/preparar/);
const app=fs.readFileSync(path.join(root,'js/app.js'),'utf8');
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'sw.js'),'utf8');
assert(app.includes('await confirmAuditOverwrite(plan)'),'Overwrites must require user consent');
assert(app.includes('await enqueue(()=>repository.putMany(replacement))'),'Batch must be atomic');
assert(app.includes('await flush();'),'Unsaved changes must be flushed first');
assert(app.includes('if(!await confirmAuditOverwrite(plan))return;'),'Cancel must exit before writes');
assert(index.includes('id="audit-import-overwrite"')&&index.includes('id="audit-import-cancel"'),'Buttons should be explicit');
assert(index.indexOf('js/audit-import-plan.js')<index.indexOf('js/app.js'),'Planner must load first');
assert(sw.includes("'./js/audit-import-plan.js'"),'Planner must be cached offline');
console.log('PASS import planner: duplicates, overwrite decision, conflict-free new records and atomic write wiring');
